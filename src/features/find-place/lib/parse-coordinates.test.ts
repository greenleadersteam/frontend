import { describe, expect, test } from 'vitest';

import { parseQuery } from './parse-coordinates';

// Координаты сравниваются с точностью до 1e-6 градуса (~0,1 м).
function expectAt(input: string, lat: number, lon: number) {
  const parsed = parseQuery(input);
  if (parsed.kind !== 'coordinates') throw new Error(`«${input}» не разобраны: ${parsed.kind}`);
  expect(parsed.lat).toBeCloseTo(lat, 6);
  expect(parsed.lon).toBeCloseTo(lon, 6);
}

describe('разбор координат', () => {
  test.each([
    ['55.7558, 37.6173'],
    ['55.7558,37.6173'],
    ['55.7558 37.6173'],
    ['55,7558 37,6173'],
    ['55,7558, 37,6173'],
    ['55,7558; 37,6173'],
    ['  55.7558 ,  37.6173  '],
  ])('десятичные: «%s»', (input) => {
    expectAt(input, 55.7558, 37.6173);
  });

  test.each([
    ['55°45′21″ 37°37′02″'],
    [`55°45'21" 37°37'02"`],
    ['55°45′21″N, 37°37′02″E'],
    ['N55°45′21″ E37°37′02″'],
    ['55°45′21″С 37°37′02″В'],
  ])('градусы, минуты, секунды: «%s»', (input) => {
    expectAt(input, 55 + 45 / 60 + 21 / 3600, 37 + 37 / 60 + 2 / 3600);
  });

  test('градусы и десятичные минуты', () => {
    expectAt('55°45,35′ 37°37,03′', 55 + 45.35 / 60, 37 + 37.03 / 60);
  });

  test('порядок — широта, долгота; буквы полушарий позволяют долготу первой', () => {
    expectAt('37.6173, 55.7558', 37.6173, 55.7558);
    expectAt('37.6173E, 55.7558N', 55.7558, 37.6173);
  });

  test('южные и западные — со знаком минус', () => {
    expectAt('33.9249 S, 18.4241 W', -33.9249, -18.4241);
    expectAt('-33.9249, -18.4241', -33.9249, -18.4241);
    // Минус из документа — типографский (U+2212).
    expectAt('−33.9249, −18.4241', -33.9249, -18.4241);
  });

  test.each([
    ['55.7558', /^Не получилось разобрать координаты/],
    ['55.7558, 37.6173, 12', /^Не получилось разобрать координаты/],
    ['95.1, 37.6', /^Широта — от −90 до 90\. Сначала широта, потом долгота/],
    ['55.1, 190', /^Долгота — от −180 до 180/],
    ['55°75′ 37°10′', /^Минуты и секунды должны быть меньше 60/],
    ['   ', /^Введите адрес или координаты/],
  ])('ошибка: «%s»', (input, message) => {
    const parsed = parseQuery(input);
    expect(parsed.kind).toBe('error');
    if (parsed.kind === 'error') expect(parsed.message).toMatch(message);
  });

  test('всё остальное — адрес', () => {
    expect(parseQuery(' Тверская улица, 13 ')).toEqual({
      kind: 'address',
      text: 'Тверская улица, 13',
    });
  });
});
